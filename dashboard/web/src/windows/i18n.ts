export function translate(locale: Locale, key: MessageKey, values?: Record<string, string | number>): string {
  const template = locale === 'ja' ? jaMessages[key] : enMessages[key]
  if (!values) return template
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, name: string) => String(values[name] ?? match))
}

export function hasMessageKey(key: string): key is MessageKey {
  return Object.prototype.hasOwnProperty.call(jaMessages, key)
}
